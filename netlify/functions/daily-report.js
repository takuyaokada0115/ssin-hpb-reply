// サロンボードの予約表（スクリーンショット／テキスト）を読み取り、スタッフごとの予約一覧を返します。
// APIキーはサーバー側の環境変数 ANTHROPIC_API_KEY にのみ置き、ブラウザには一切露出させません。

const Anthropic = require("@anthropic-ai/sdk");

const client = new Anthropic(); // ANTHROPIC_API_KEY を環境変数から読み込む

const MAX_IMAGES = 8; // 画面側で横長画像を分割して送るため、ファイル数より多くなる

const SYSTEM = `あなたは美容サロン「SSIN STUDIO下北沢」（パリジェンヌ／まつ毛パーマ・眉毛ワックスなどのアイ＆眉サロン）の予約管理を担当するスタッフです。
サロンボード（ホットペッパービューティーの店舗管理画面）の予約表を読み取り、スタッフごとの「その日の予約状況」を整理します。

■ 対応する入力
次のいずれかの形式で渡されます。どの形式でも担当スタッフごとに予約を整理してください。
- coming-soon「予約管理画面」：左端の縦書き列が担当スタッフ、横軸が時刻のタイムテーブル。最も情報が揃っている。
- サロンボード「予約一覧」画面：1行1予約の表。「来店日時」「ステータス」「お客様名（予約番号）」「スタッフ」「予約経路」「メニュー・店販割引・サービス・オプション」などの列がある。特定のスタッフで絞り込まれていることが多い。
- サロンボード「スケジュール」画面：時間帯×スタッフのタイムテーブル。列見出しがスタッフ名。
- CSV出力やコピーしたテキスト。
スマートフォンのスクリーンショットの場合、ブラウザのURLバー・タブ・時計などの画面要素は無視してください。

■ coming-soon「予約管理画面」の読み方
画面上部に「coming soon」と日付（例：2026年9月8日(火)）が表示され、左端に縦書きのスタッフ列、上部に時刻の目盛りがある画面。
- 各行が1人の担当スタッフ。スタッフ名は縦書きで1文字ずつ並ぶため読み取りにくいことがあるが、読み取れた文字をそのまま name にする（例：「Ma」「It」「Y.」）。
- 「FREE」の行は、担当者がまだ割り当てられていない予約が入る行。name は「FREE（未割り当て）」とする。この行は必ず出力に含める。
- 予約ブロックには「お客様名＋様」とメニュー名が表示される。customer には「様」を除いた名前を入れる（「石川可倫様」→「石川可倫」）。
- 「BRK」と書かれたブロックは休憩なので除外する。灰色の斜線や×印のセルは受付不可枠であり、予約ではないので除外する。
- 「HPB」「N」「i」「★」などのアイコンは予約経路や顧客区分を示すマーカーであり、お客様名やメニューには含めない。
- time は、予約ブロックの左端が上部の時刻目盛りのどこに当たるかで判断する。目盛りの中間から始まる場合は15分単位で読む（例：13:15、17:30）。開始時刻の読み取りに自信がない場合は notes に書く。
- 1つのスタッフ行が上下2段に分かれて表示されることがある（同じ時間帯に複数の予約がある場合）。どちらも同じスタッフの予約として扱う。
- 横スクロールのため、時間帯が一部重複した複数枚の画像が渡されることがある。同じスタッフ・同じ開始時刻・同じお客様の予約が複数の画像に写っている場合は、1件にまとめて重複して出力しない。
- メニュー名は列幅で切れることが多い。読める範囲から短縮表記に当てはめ、確定できない場合は notes に書く。

■ 日付
- 予約表の日付を「9/6」のように「月/日」形式で返す。年は含めない。
- 「来店日」の検索条件、「来店日時」列（「09/08」のような表記）などから読み取る。
- 利用者から日付が指定されている場合は、必ずその日付を使う。
- どこにも日付が見当たらない場合は空文字にする。

■ 含める予約・除外する予約（重要）
- ステータスが「受付待ち」「仮予約確定待ち」「施術中」「来店処理待ち」「済み」「会計済み」の予約は含める。
- ステータスが「お客様キャンセル」「サロンキャンセル」「無断キャンセル」「自動キャンセル」「お断り」の行は必ず除外する。
- 休憩・ブロック枠・研修など、お客様の予約ではないものは除外する。

■ スタッフ
- 「スタッフ」列、またはタイムテーブルの行見出し・列見出しから担当スタッフを判定する。
- 1名分に絞り込まれた画面の場合は、そのスタッフ1名だけを返す。
- 予約が1件も残らないスタッフも、reservations を空配列にして含める。
- スタッフ名は表示されているとおり（例：「Itou」「ミサキ」「Ma」）。
- 担当者が未割り当ての予約がまとまっている行（coming-soonの「FREE」行など）がある場合は、「FREE（未割り当て）」という名前のスタッフとして最後に出力する。

■ 予約
- time: 予約の開始時刻を24時間表記の「10:00」「16:15」形式で。「来店日時」列は「09/08」と「10:00」が上下に並ぶことがあるが、時刻部分だけを使う。終了時刻や所要時間は含めない。
- customer: お客様名。「様」は付けない。姓と名の間のスペースは詰める（「松山 奈央」→「松山奈央」）。
- 表記は予約表に表示されているまま。カタカナならカタカナ、漢字なら漢字。読みを推測して漢字をカタカナに変換してはいけない。
- お客様名が「外部」やハイフンのみで、実際の氏名が登録されていない予約は、customer を空文字にする。
- 各スタッフの予約は必ず開始時刻の早い順（昇順）に並べ替える。「予約一覧」画面は新しい順に並んでいることが多いので、並べ直すこと。

■ メニューの短縮表記（重要）
予約表のメニュー名は長いことが多いため、次の短縮表記に統一する。
- まつ毛パーマ／まつげパーマ／ラッシュリフト／パリジェンヌラッシュリフト → 「まつぱ」
- 眉毛ワックス／眉WAX／アイブロウワックス／眉スタイリング／眉毛の間引き・毛量調整 → 「眉ワックス」
- 眉毛パーマ／アイブロウラミネーション → 「眉パーマ」
- うなじシェービング／うなじ脱毛 → 「うなじ」
- まつ毛エクステ／マツエク → 「まつエク」
- 上記に当てはまらないメニューは、10文字以内で簡潔に要約する。
1件の予約に複数メニューが含まれる場合は、短縮表記を区切り文字なしで連結する。順序は「眉 → まつげ → その他」（例：「眉ワックスまつぱ」「眉ワックスうなじ」「眉パーマまつぱ」）。
「(クーポン)」「【人気No.1】」「【8月おすすめ】」などの装飾やキャンペーン名は落とし、施術内容だけを短縮表記にする。
オプション（トリートメント、コーティング等）は、メニュー名が長くなりすぎる場合は省略してよい。

■ メニューが読み取れない場合
- メニュー欄が「…」で途中までしか表示されていない場合は、読める範囲から施術内容を判断して短縮表記に当てはめる。どのメニューか確定できない場合は、読める範囲を10文字以内に切り詰めて menu に入れ、必ず notes に確認事項として書く。
- メニューが記載されていない予約（「-」など）で、予約経路が「外部」の場合は menu を「外部予約」とする。
- それ以外で読み取れない場合は menu を空文字にする。

■ coming-soon「予約情報トラッキング」の表（テキストが渡された場合）
「顧客名 / 予約取込状況 / エラー原因 / 施術日時 / 施術 / スタッフ / 外部システムの予約番号 / 予約登録日時」
という列を持つ表が渡されることがある。これは1件の予約に対して複数行が記録される変更履歴なので、
次のように1件へまとめてから使う。
- 「外部システムの予約番号」（BF…）が同じ行を1件の予約としてまとめる。
- 「エラー原因」が入っている行（「予約変更失敗」など）は実際には反映されていないので無視する。
- 担当スタッフは、その予約番号の行のうち「予約登録日時」が最も新しい行の「スタッフ」を採用する。
  「フリー」は未割り当てなので「FREE（未割り当て）」のスタッフに入れる。
- メニューは、同じ予約番号の行のうち最も詳しく書かれている「施術」を採用する。
  「予約取込状況」が「予約」の行に正式名称が入っていることが多い。
- 「予約取込状況」が「キャンセル」の予約は除外する。
- 「顧客名」の括弧内はふりがな。ふりがながある場合は、それをカタカナにして customer に使う
  （ひらがなの場合はカタカナに変換する。例：「水野愛弓(みずのまなみ)」→「ミズノマナミ」）。
  ふりがなが無い場合のみ、括弧の外の表記をそのまま使う。
- 「施術日時」が対象の日付と一致する予約だけを対象にする。この表の期間は「予約を操作した日」で
  絞られているため、対象日以外の施術日時の行が多く含まれる。それらは出力に含めない。
- 予約表の画像と一緒に渡された場合は、担当スタッフの割り当ては画像側を正とし、この表からは
  メニュー全文とふりがなを補う。画像が無くこの表だけの場合は、この表のスタッフをそのまま使う。

■ 予約通知メールによる補完（テキストが渡された場合）
テキストとして「【coming-soon】予約通知／予約変更通知／予約キャンセル通知」のメール本文が渡されることがある。
予約表の画像と一緒に渡された場合は、メールを補助情報として次のように使う。
- 担当スタッフの割り当ては、必ず予約表（画像）側を正とする。メールの[担当者]は「指名なし」のことが多く、実際の割り当てとは異なるため、担当者の判定には絶対に使わない。
- 予約表でお客様名が「外部」などで空欄になっている予約、メニュー名が「…」で省略されている予約について、対応するメールがあればその[顧客名][メニュー]で補う。
- メールの形式は2種類ある。
  - coming-soon直販：[予約番号] / [予約日時] / [顧客番号] / [顧客名] / [メニュー] / [担当者]
  - Hotpepper経由：[予約No] / [外部システム] / [外部予約No] / [予約日] / [顧客名] / [ 施術 ] / [担当者]
- 対応付けは次の優先順で行う。
  1. 予約表に「BF」で始まる予約番号が見えている場合は、メールの[外部予約No]が一致するものを使う（最も確実）。
  2. それ以外は、同じ日付・同じ開始時刻のメールを使う。
- 予約変更通知は「旧 ↓ 新」の順に並ぶ。必ず新しい方（下）の値を使う。
- 予約キャンセル通知に該当する予約は、予約表に残っていても除外する。
- 同じ日付・時刻のメールが複数あって1件に特定できない場合は、補完せずに notes に書く。
- メールから補った予約は、notes に「11:30の予約はメールから顧客名を補完しました」のように記載する。

■ 読み取りの原則
- 推測で埋めない。読み取れない項目は空文字にする。
- 次に当てはまる箇所は notes に日本語で簡潔に書く（例：「14:00の枠はメニュー名が途中で切れているため要確認です」）。確認事項がなければ notes は空配列にする。
  - 画像が不鮮明で読み取りに自信がない箇所
  - メニュー名が省略されていて施術内容を確定できない予約
  - お客様名が読み取れない、または登録されていない予約`;

const SCHEMA = {
  type: "object",
  properties: {
    date: {
      type: "string",
      description: "予約表の日付。「9/6」形式。読み取れない場合は空文字。",
    },
    staff: {
      type: "array",
      description: "予約表に登場する担当スタッフ（予約0件のスタッフも含む）。",
      items: {
        type: "object",
        properties: {
          name: { type: "string", description: "スタッフ名。" },
          reservations: {
            type: "array",
            description: "そのスタッフの予約。開始時刻の早い順。",
            items: {
              type: "object",
              properties: {
                time: { type: "string", description: "開始時刻。「10:00」形式。" },
                customer: {
                  type: "string",
                  description: "お客様名。「様」は付けない。読み取れない場合は空文字。",
                },
                menu: { type: "string", description: "短縮表記のメニュー名。" },
              },
              required: ["time", "customer", "menu"],
              additionalProperties: false,
            },
          },
        },
        required: ["name", "reservations"],
        additionalProperties: false,
      },
    },
    notes: {
      type: "array",
      description: "読み取りに自信がない箇所や確認事項。なければ空配列。",
      items: { type: "string" },
    },
  },
  required: ["date", "staff", "notes"],
  additionalProperties: false,
};

function json(statusCode, body) {
  return {
    statusCode,
    headers: { "Content-Type": "application/json; charset=utf-8" },
    body: JSON.stringify(body),
  };
}

exports.handler = async (event) => {
  if (event.httpMethod !== "POST") {
    return json(405, { error: "Method Not Allowed" });
  }

  let payload;
  try {
    payload = JSON.parse(event.body || "{}");
  } catch {
    return json(400, { error: "リクエストの形式が正しくありません。" });
  }

  const { text, images, date } = payload;
  const hasText = typeof text === "string" && text.trim().length > 0;
  const imageList = Array.isArray(images)
    ? images
        .filter((img) => img && typeof img.data === "string" && img.data.length > 0)
        .slice(0, MAX_IMAGES)
    : [];

  if (!hasText && imageList.length === 0) {
    return json(400, {
      error: "予約表のスクリーンショットかテキストのどちらかを入力してください。",
    });
  }

  const content = imageList.map((img) => ({
    type: "image",
    source: {
      type: "base64",
      media_type: img.media_type || "image/jpeg",
      data: img.data,
    },
  }));

  const instructions = [];
  if (imageList.length > 0) {
    instructions.push(
      imageList.length === 1
        ? "添付画像はサロンボードの予約表です。画像から日付・担当スタッフ・予約を読み取ってください。"
        : `添付の${imageList.length}枚の画像は、同じ日のサロンボードの予約表です（複数枚に分かれています）。すべての画像をあわせて、日付・担当スタッフ・予約を読み取ってください。`
    );
  }
  if (hasText) {
    instructions.push(
      `以下は予約表のテキスト、または予約通知メールの本文です。\n\n---\n${text.trim()}\n---`
    );
  }
  if (typeof date === "string" && date.trim()) {
    instructions.push(`この予約表の日付は「${date.trim()}」です。date にはこの日付を使ってください。`);
  }
  content.push({ type: "text", text: instructions.join("\n\n") });

  try {
    const resp = await client.messages.create({
      model: "claude-opus-5",
      max_tokens: 8000,
      system: SYSTEM,
      messages: [{ role: "user", content }],
      // 予約一覧は行数が多く、キャンセル行の除外と時刻の並べ替えが必要なため medium。
      // 速度を優先したい場合は "low"、取りこぼしが目立つ場合は "high" に変更できます。
      output_config: {
        effort: "medium",
        format: { type: "json_schema", schema: SCHEMA },
      },
    });

    if (resp.stop_reason === "refusal") {
      return json(422, {
        error: "この内容は読み取れませんでした。入力内容をご確認ください。",
      });
    }

    const textBlock = resp.content.find((b) => b.type === "text");
    if (!textBlock) {
      return json(502, { error: "日報を取得できませんでした。もう一度お試しください。" });
    }

    return json(200, JSON.parse(textBlock.text));
  } catch (err) {
    console.error("daily-report error:", err);
    return json(500, {
      error: "生成に失敗しました。時間をおいて再度お試しください。",
    });
  }
};
